/**
 * 통합 불용어 세트 반환
 */
export function getLegalStopwords(
  mode: "strict" | "standard" | "aggressive" = "standard"
): Set<string> {
  const result = new Set<string>();

  // 항상 포함
  KOREAN_PARTICLES.forEach((w) => result.add(w));
  VERB_ENDINGS.forEach((w) => result.add(w));
  SINO_KOREAN_FORMULA.forEach((w) => result.add(w));

  if (mode === "standard" || mode === "aggressive") {
    LEGAL_FORMULA_STOPWORDS.forEach((w) => result.add(w));
  }

  if (mode === "aggressive") {
    LEGAL_PROCEDURE_TERMS.forEach((w) => result.add(w));
  }

  // 보호 목록은 절대 불용어에 포함 안 함
  LEGAL_CORE_TERMS_PROTECT.forEach((w) => result.delete(w));

  return result;
}

/**
 * 특정 단어가 법률 핵심 용어인지 확인
 */
export function isLegalCoreTerm(word: string): boolean {
  return LEGAL_CORE_TERMS_PROTECT.has(word);
}

/**
 * 불용어 사전 통계
 */
export function getStopwordStats(): {
  particles: number;
  verbEndings: number;
  formulaic: number;
  procedure: number;
  protected: number;
  total: (mode: "strict" | "standard" | "aggressive") => number;
} {
  return {
    particles: KOREAN_PARTICLES.size,
    verbEndings: VERB_ENDINGS.size,
    formulaic: LEGAL_FORMULA_STOPWORDS.size,
    procedure: LEGAL_PROCEDURE_TERMS.size,
    protected: LEGAL_CORE_TERMS_PROTECT.size,
    total: (mode) => getLegalStopwords(mode).size,
  };
}
